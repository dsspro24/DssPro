Pakartotinumas nustatomas pagal ANK sąlygas ir konkretaus atvejo aplinkybes – ne kiekvienas atskirai aptiktas trūkumas savaime reiškia pakartotinį nusižengimą. Vis dėlto anksčiau nustatyto pažeidimo nepašalinimas arba tos pačios priežasties leidimas kartotis didina teisinių ir veiklos pasekmių riziką. Po patikrinimo verta taisyti ne tik konkretų trūkumą, bet ir jo priežastį: atnaujinti instrukciją, papildomai instruktuoti darbuotojus ar pakeisti darbo organizavimą.

