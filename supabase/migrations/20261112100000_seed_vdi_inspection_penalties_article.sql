## Kaip VDI tikrina darbuotojų saugą?

VDI priežiūra gali apimti planinius ir neplaninius patikrinimus, taip pat aplinkybių vertinimą po pranešimo apie galimą pažeidimą ar nelaimingą atsitikimą darbe. Patikrinimo metu svarbu ne tik pateikti dokumentus, bet ir parodyti, kaip saugos reikalavimai vykdomi konkrečioje darbo vietoje.

Inspektoriai gali vertinti:

- ar profesinės rizikos vertinimas atliktas, atnaujintas ir jo priemonės įgyvendinamos;
- ar darbuotojai instruktuoti pagal atliekamą darbą, įrangą ir darbo vietos pavojus;
