## ANK 96 straipsnis: kokios baudos gresia vadovui?

ANK 96 straipsnyje atskiriamas įprastas darbuotojų saugos ir sveikatos reikalavimų pažeidimas nuo pažeidimo, dėl kurio galėjo įvykti nelaimingas atsitikimas darbe ar avarija. Vadovui ir kitam atsakingam asmeniui numatytos šios pagrindinės baudų ribos:

- Už bendrą DSS norminių teisės aktų pažeidimą (ANK 96 straipsnio 1 dalis) – nuo 140 iki 300 eurų.
- Jei pažeidimas galėjo sukelti nelaimingą atsitikimą darbe ar avariją (ANK 96 straipsnio 2 dalis) – nuo 300 iki 860 eurų.
- Už pakartotinį bendrą pažeidimą (ANK 96 straipsnio 3 dalis) – nuo 300 iki 860 eurų.
- Pakartotinai padarius pažeidimą, dėl kurio galėjo įvykti nelaimingas atsitikimas darbe ar avarija (ANK 96 straipsnio 4 dalis), – nuo 1 000 iki 2 000 eurų.

Tai įstatyme nustatyti baudų intervalai, o ne automatiškai kiekvienu atveju skiriama konkreti suma. Atsakomybę nagrinėjanti institucija vertina faktines aplinkybes ir taikytiną ANK nuostatą. Vien vadovo pareigų pavadinimas savaime nereiškia, kad jis atsako už kiekvieną trūkumą – svarbu, kam pagal funkcijas buvo pavesta užtikrinti atitinkamą reikalavimą.

## Ką reiškia pažeidimas, galėjęs sukelti nelaimingą atsitikimą?

Didesnė atsakomybė gali būti taikoma ir tada, kai nelaimingas atsitikimas ar avarija faktiškai neįvyko. Vertinama, ar nustatytas DSS reikalavimų pažeidimas galėjo sukelti tokį įvykį. Pavyzdžiui, neapsaugota pavojinga įranga, nepažymėta rizikinga zona ar netinkamai organizuotas pavojingas darbas gali kelti realų pavojų, net jei darbuotojas nesusižalojo.

Todėl prevencija svarbesnė už dokumentų tvarkymą po patikrinimo: nustačius pavojų reikia imtis apsaugos priemonių, paskirti atsakingą asmenį ir įsitikinti, kad priemonė iš tikrųjų veikia.

## Pakartotiniai DSS pažeidimai: kada bauda didėja?

