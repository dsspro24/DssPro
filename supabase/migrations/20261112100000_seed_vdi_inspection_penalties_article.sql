Darbuotojų sauga ir sveikata (DSS) nėra vien dokumentų aplankas. Tai kasdienė sistema, padedanti apsaugoti darbuotojus ir įmonę nuo nelaimingų atsitikimų, prastovų, reputacinės žalos ir administracinių baudų. Valstybinė darbo inspekcija (VDI) tikrina, ar sauga užtikrinama realiai, o ne tik patvirtinta parašais.

